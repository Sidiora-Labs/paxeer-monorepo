def test_no_daemon_consumer_of_retired_kernel_symbols():
    for relative_path in RETIRED_PATHS:
        path = ROOT / relative_path
        assert not path.exists(), f"Retired path still exists: {relative_path}"
        assert not path.is_symlink(), f"Retired path is a symlink: {relative_path}"

    recipes = subprocess.run(
        ["make", "-n", "build", "test"],
        cwd=ROOT,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        timeout=120,
        check=False,
    )
    assert recipes.returncode == 0, recipes.stdout
    for retired in (*RETIRED_BINARIES, *RETIRED_PATHS):
        assert retired not in recipes.stdout, (
            f"Build recipe still names {retired}:\n{recipes.stdout}"
        )

    build = subprocess.run(
        ["go", "vet", "./daemon/..."],
        cwd=ROOT,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        timeout=600,
        check=False,
    )
    assert build.returncode == 0, build.stdout
