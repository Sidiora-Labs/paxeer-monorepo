#!/usr/bin/env python3
"""Validate and atomically publish statik output under the swagger namespace."""

import os
from pathlib import Path
import re
import sys
import tempfile


def namespace(source):
    if not source.startswith("// Code generated by statik. DO NOT EDIT.\n"):
        raise ValueError("missing statik generation header")
    if len(re.findall(r"(?m)^package swagger$", source)) != 1:
        raise ValueError("unexpected statik package")
    if len(re.findall(r"(?m)^func init\(\) \{$", source)) != 1:
        raise ValueError("unexpected statik initializer")
    if len(re.findall(r'(?m)^\s*data := "', source)) != 1:
        raise ValueError("missing embedded asset data")
    pattern = r'(?m)^\tfs\.Register(?:\(data\)|WithNamespace\("swagger", data\))$'
    result, count = re.subn(pattern, '\tfs.RegisterWithNamespace(swaggerNamespace, data)', source)
    if count != 1:
        raise ValueError("expected exactly one default or swagger namespace registration")
    if "swaggerNamespace" in source:
        raise ValueError("unexpected existing namespace declaration")
    result = result.replace("func init() {", 'const swaggerNamespace = "swagger"\n\nfunc init() {', 1)
    return result.replace("// Package statik contains static assets.", "// Package swagger contains static assets.", 1)


def publish(source, destination):
    data = namespace(Path(source).read_text()).encode()
    destination = Path(destination)
    fd, temporary = tempfile.mkstemp(dir=destination.parent, prefix=".statik-")
    try:
        with os.fdopen(fd, "wb") as stream:
            stream.write(data)
            stream.flush()
            os.fsync(stream.fileno())
        os.chmod(temporary, 0o644)
        os.replace(temporary, destination)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


if __name__ == "__main__":
    try:
        publish(*sys.argv[1:])
    except (ValueError, OSError, TypeError) as error:
        sys.exit(f"swagger generation: {error}")
