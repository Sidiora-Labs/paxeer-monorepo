static int next_source_token(FILE *source, char *identifier, size_t capacity)
{
    int c;

    while ((c = fgetc(source)) != EOF) {
        if (c == '/') {
            int following = fgetc(source);
            if (following == '/') {
                while ((c = fgetc(source)) != EOF && c != '\n') {}
                continue;
            }
            if (following == '*') {
                int previous = 0;
                while ((c = fgetc(source)) != EOF) {
                    if (previous == '*' && c == '/') break;
                    previous = c;
                }
                if (c == EOF) return -1;
                continue;
            }
            if (following != EOF && ungetc(following, source) == EOF)
                return -1;
            continue;
        }
        if (c == '\"' || c == '\'' || c == '`') {
            int quote = c;
            while ((c = fgetc(source)) != EOF) {
                if (c == quote) break;
                if (c == '\\' && quote != '`' && fgetc(source) == EOF)
                    return -1;
            }
            if (c == EOF) return -1;
            continue;
        }
        if (isalpha((unsigned char)c) || c == '_') {
            size_t length = 0U;
            do {
                if (length + 1U >= capacity) return -1;
                identifier[length++] = (char)c;
                c = fgetc(source);
            } while (c != EOF && (isalnum((unsigned char)c) || c == '_'));
            identifier[length] = '\0';
            if (c != EOF && ungetc(c, source) == EOF) return -1;
            return 1;
        }
        if (!isspace((unsigned char)c)) {
            if (capacity < 2U) return -1;
            identifier[0] = (char)c;
            identifier[1] = '\0';
            return 1;
        }
    }
    return ferror(source) ? -1 : 0;
}

static int next_go_function_name(FILE *source, char *name, size_t capacity)
{
    char token[256];
    int result;

    while ((result = next_source_token(source, token, sizeof(token))) > 0) {
        if (strcmp(token, "func") != 0) continue;
        result = next_source_token(source, token, sizeof(token));
        if (result <= 0) return -1;
        if (strcmp(token, "(") == 0) {
            size_t depth = 1U;
            while (depth != 0U) {
                result = next_source_token(source, token, sizeof(token));
                if (result <= 0) return -1;
                if (strcmp(token, "(") == 0) ++depth;
                if (strcmp(token, ")") == 0) --depth;
            }
            result = next_source_token(source, token, sizeof(token));
            if (result <= 0) return -1;
        }
        if (!isalpha((unsigned char)token[0]) && token[0] != '_') continue;
        if (strlen(token) >= capacity) return -1;
        (void)memcpy(name, token, strlen(token) + 1U);
        result = next_source_token(source, token, sizeof(token));
        if (result <= 0) return -1;
        if (strcmp(token, "(") == 0) return 1;
    }
    return result;
}

static int identifier_is_retired(const char *identifiers, const char *name)
{
    size_t length = strlen(name);
    const char *entry = identifiers;

    while (*entry != '\0') {
        const char *end = strchr(entry, ' ');
        size_t entry_length = end == NULL ? strlen(entry) : (size_t)(end - entry);
        if (entry_length == length && memcmp(entry, name, length) == 0)
            return 1;
        if (end == NULL) break;
        entry = end + 1;
    }
    return 0;
}

static int retired_surface_absent(const retired_surface *surface)
{
    struct stat status;
    FILE *source;
    char identifier[256];
    int result;
    int absent = 1;

    if (lstat(surface->path, &status) != 0) {
        if (errno == ENOENT) return 0;
        fprintf(stderr, "%s: cannot inspect %s: %s\n",
                surface->interface_id, surface->path, strerror(errno));
        return 1;
    }
    if (surface->identifiers == NULL) {
        fprintf(stderr, "%s: retired format path still exists: %s\n",
                surface->interface_id, surface->path);
        return 1;
    }
    if (!S_ISREG(status.st_mode)) {
        fprintf(stderr, "%s: expected a regular source file: %s\n",
                surface->interface_id, surface->path);
        return 1;
    }
    source = fopen(surface->path, "r");
    if (source == NULL) {
        fprintf(stderr, "%s: cannot read %s: %s\n",
                surface->interface_id, surface->path, strerror(errno));
        return 1;
    }
    while ((result = surface->go_function ?
            next_go_function_name(source, identifier, sizeof(identifier)) :
            next_source_token(source, identifier, sizeof(identifier))) > 0) {
        if (identifier_is_retired(surface->identifiers, identifier)) {
            fprintf(stderr, "%s: retired identifier %s remains at %s "
                    "(catalogue line %u)\n", surface->interface_id,
                    identifier, surface->path, surface->line);
            absent = 0;
        }
    }
    if (result < 0 || ferror(source)) {
        fprintf(stderr, "%s: cannot tokenize %s\n",
                surface->interface_id, surface->path);
        absent = 0;
    }
    if (fclose(source) != 0) {
        fprintf(stderr, "%s: cannot close %s\n",
                surface->interface_id, surface->path);
        absent = 0;
    }
    return absent ? 0 : 1;
}

static int kernel_completion_retired_surfaces_absent(void)
{
    size_t failures = 0U;
    size_t i;

    for (i = 0U; i < sizeof(retired_surfaces) / sizeof(retired_surfaces[0]); ++i)
        failures += (size_t)retired_surface_absent(&retired_surfaces[i]);
    for (i = 0U; i < sizeof(planned_paths) / sizeof(planned_paths[0]); ++i) {
        struct stat status;
        FILE *source;

        if (stat(planned_paths[i], &status) != 0) {
            fprintf(stderr, "planned path unavailable: %s: %s\n",
                    planned_paths[i], strerror(errno));
            ++failures;
            continue;
        }
        if (!S_ISREG(status.st_mode)) {
            fprintf(stderr, "planned path is not a regular file: %s\n",
                    planned_paths[i]);
            ++failures;
            continue;
        }
        source = fopen(planned_paths[i], "r");
        if (source == NULL) {
            fprintf(stderr, "planned path is unreadable: %s: %s\n",
                    planned_paths[i], strerror(errno));
            ++failures;
        } else if (fclose(source) != 0) {
            fprintf(stderr, "cannot close planned path: %s\n", planned_paths[i]);
            ++failures;
        }
    }
    printf("kernel completion: checked %zu retired interfaces and %zu planned paths\n",
           sizeof(retired_surfaces) / sizeof(retired_surfaces[0]),
           sizeof(planned_paths) / sizeof(planned_paths[0]));
    LXP_CASE_CHECK(failures == 0U);
    return 0;
}

int main(int argc, char **argv)
{
    const lxp_kernel_case cases[] = {
        { "kernel_completion_retired_surfaces_absent",
          kernel_completion_retired_surfaces_absent }
    };

    return lxp_kernel_case_main(cases, sizeof(cases) / sizeof(cases[0]),
                               argc, argv);
}
