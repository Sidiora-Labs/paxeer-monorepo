import subprocess
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parents[2]


def test_no_tracked_node_modules():
    result = subprocess.run(
        ["git", "ls-files", "--full-name", "-z"],
        cwd=REPO_ROOT,
        check=True,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="surrogateescape",
    )
    tracked_paths = [path for path in result.stdout.split("\0") if path]
    assert tracked_paths, "Git reported no tracked files"
    offenders = [path for path in tracked_paths if "node_modules" in path.split("/")]
    assert not offenders, "Installed node_modules files remain tracked:\n" + "\n".join(
        offenders
    )
