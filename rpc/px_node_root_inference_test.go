func pxInferenceWire(t *testing.T, raw string) []byte {
	t.Helper()
	b, err := hex.DecodeString(raw)
	require.NoError(t, err)
	return b
}
func pxInferenceJSON(t *testing.T, v interface{}) interface{} {
	t.Helper()
	raw, err := json.Marshal(v)
	require.NoError(t, err)
	var value interface{}
	require.NoError(t, json.Unmarshal(raw, &value))
	return value
}

func TestPxNodeRootInferenceDecoders(t *testing.T) {
	id := func(n string) string { return strings.Repeat(n, 32) }
	room, err := evmrpc.DecodePxInferenceRoom(pxInferenceWire(t, pxInferenceRoomWire))
	require.NoError(t, err)
	require.Equal(t, map[string]interface{}{"room_id": id("01"), "host_key": id("02"), "model_digest": id("03"), "runtime_digest": id("04"), "profile": map[string]interface{}{"minimum_bond": "100", "canary_ratio_bps": uint64(100), "lap_size_tokens": "32", "challenge_window_blocks": "10", "slash_fraction_bps": uint64(500), "host_share_bps": uint64(1000), "protocol_share_bps": uint64(100), "settlement_account": id("05")}, "state": uint64(0), "opened_at_epoch": "6", "open_asks": []string{id("07")}, "open_bids": []string{id("08")}}, room)
	room["ask_streams"] = []interface{}{map[string]interface{}{"ask_id": id("07"), "stream_id": id("00"), "stream": nil}}
	pxRootAssertSchema(t, "px_getInferenceRoom", pxInferenceJSON(t, room))
	pxRootAssertSchema(t, "px_getInferenceRooms", pxInferenceJSON(t, []interface{}{room}))
	deal, err := evmrpc.DecodePxInferenceDeal(pxInferenceWire(t, pxInferenceDealWire))
	require.NoError(t, err)
	require.Equal(t, map[string]interface{}{"room_id": id("01"), "deal_id": id("09"), "ask_id": id("07"), "agreed_price_per_thousand_tokens": "2500", "roster_digest": id("0a"), "state": uint64(1), "layers": []map[string]interface{}{{"bid_id": id("08"), "first_layer": uint64(0), "end_layer": uint64(16)}, {"bid_id": id("0b"), "first_layer": uint64(16), "end_layer": uint64(32)}}, "settled_tokens": "9007199254740993", "settled_amount_owed": "1329227995784915872903807060280344583"}, deal)
	pxRootAssertSchema(t, "px_getInferenceDeal", pxInferenceJSON(t, deal))
	peer, err := evmrpc.DecodePxInferencePeer(pxInferenceWire(t, pxInferencePeerWire))
	require.NoError(t, err)
	require.Equal(t, map[string]interface{}{"peer_key": id("0c"), "worker": id("0d"), "delegate": id("0e"), "metadata": id("0f"), "generation": "1", "key_version": "2", "metadata_revision": "3", "valid_from": "4", "expiry": "100", "state": uint64(2), "enrolled": true, "capabilities_status": uint64(4), "capabilities": nil, "bond_status": uint64(2), "fault_count": uint64(9)}, peer)
	peer["attestation_binding"] = map[string]interface{}{"family": uint8(0), "model_digest": id("00"), "runtime_digest": id("00"), "block_height": "0"}
	pxRootAssertSchema(t, "px_getInferencePeer", pxInferenceJSON(t, peer))
	receipt, err := evmrpc.DecodePxInferenceReceipt(pxInferenceWire(t, pxInferenceReceiptWire))
	require.NoError(t, err)
	require.Equal(t, map[string]interface{}{"deal_id": id("09"), "first_lap_index": "4", "last_lap_index": "7", "cumulative_tokens": "9007199254740993", "batch_digest": id("10"), "countersign_quorum": uint64(2)}, receipt)
	pxRootAssertSchema(t, "px_getInferenceReceipts", pxInferenceJSON(t, []interface{}{receipt}))
	for _, test := range []struct {
		name, raw string
		decode    func([]byte) (map[string]interface{}, error)
	}{{"room", pxInferenceRoomWire, evmrpc.DecodePxInferenceRoom}, {"deal", pxInferenceDealWire, evmrpc.DecodePxInferenceDeal}, {"peer", pxInferencePeerWire, evmrpc.DecodePxInferencePeer}, {"receipt", pxInferenceReceiptWire, evmrpc.DecodePxInferenceReceipt}} {
		t.Run(test.name, func(t *testing.T) {
			raw := pxInferenceWire(t, test.raw)
			before := bytes.Clone(raw)
			_, err := test.decode(raw[:len(raw)-1])
			require.Error(t, err)
			_, err = test.decode(append(bytes.Clone(raw), 0))
			require.Error(t, err)
			require.Equal(t, before, raw)
		})
	}
}

