// Typed argument decoding belongs to the shared JSON-RPC server. Assert its
// precise diagnostic as well as the handler's documented Invalid params error.
func pxHistoryParamMessage(method string, args []interface{}) string {
	required, limitIndex := 1, 2
	if method == "px_listHolderRecords" {
		required = 2
		limitIndex = 3
	}
	if len(args) < required {
		return fmt.Sprintf("missing value for required argument %d", len(args))
	}
	if len(args) > 4 {
		return "too many arguments, want at most 4"
	}
	if len(args) > limitIndex {
		switch args[limitIndex].(type) {
		case float64:
			return fmt.Sprintf("invalid argument %d: json: cannot unmarshal number 1.5 into Go value of type int", limitIndex)
		case string:
			return fmt.Sprintf("invalid argument %d: json: cannot unmarshal string into Go value of type int", limitIndex)
		}
	}
	return "Invalid params"
}
