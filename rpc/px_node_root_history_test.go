func TestPxNodeRoot_History_MergePositionBoundaries(t *testing.T) {
	replay := newPxHistoryReplay(t)
	endpoint, err := url.Parse(replay.server.URL)
	require.NoError(t, err)
	source := history.Client{Endpoint: endpoint}
	account := history.Account{Side: "paxeer", Account: pxHistoryAddress}
	first, err := source.Page(t.Context(), account, history.Query{Limit: 2})
	require.NoError(t, err)
	rest, err := source.Page(t.Context(), account, history.Query{Cursor: first.Next, Limit: 2})
	require.NoError(t, err)
	merged, err := history.Merge([]history.Page{first, rest, first}, []history.Account{account, account, account}, 3, true)
	require.NoError(t, err)
	require.Len(t, merged.Items, 3, "the same indexed row returned through two account keys must be deduplicated")
	require.Equal(t, []string{"3", "6", "9"}, []string{merged.Items[0].ID, merged.Items[1].ID, merged.Items[2].ID})
	require.Equal(t, merged.Items[2].Position(), *merged.Next)
	require.Equal(t, "paxeer", merged.Items[0].Side)
	empty := history.Page{Items: []history.Row{}, IndexedHeight: nil}
	complete, err := source.Page(t.Context(), account, history.Query{Limit: 100})
	require.NoError(t, err)
	// Side identifies the queried half of a unified account. It is independent
	// of chain: a Paxeer precompile can record a native account's transfer.
	nativeSide := history.Account{Side: "layerx", Account: pxHistoryAddress}
	nativePage, err := source.Page(t.Context(), nativeSide, history.Query{Limit: 100})
	require.NoError(t, err)
	tagged, err := history.Merge([]history.Page{nativePage}, []history.Account{nativeSide}, 100, true)
	require.NoError(t, err)
	require.Equal(t, "layerx", tagged.Items[0].Side)
	require.Equal(t, "paxeer", tagged.Items[0].Chain)

	result, err := history.Merge([]history.Page{complete, empty}, []history.Account{account, {Side: "layerx", Account: "a-native-account-before-its-first-indexed-block"}}, 100, true)
	require.NoError(t, err)
	require.Len(t, result.Items, 4)
	require.Nil(t, result.IndexedHeight, "a side which has not indexed a block must keep aggregate freshness null")
	require.Nil(t, result.Next)
}

func TestPxNodeRoot_History_Metrics(t *testing.T) {
	reader := sdkmetric.NewManualReader()
	provider := sdkmetric.NewMeterProvider(sdkmetric.WithReader(reader))
	t.Cleanup(func() { require.NoError(t, provider.Shutdown(context.Background())) })
	histogram, err := provider.Meter("px-history-test").Float64Histogram("px_history_latency")
	require.NoError(t, err)
	t.Cleanup(evmrpc.SwapRequestLatencyForTest(histogram))
	replay := newPxHistoryReplay(t)
	h := newPxRootAccountHarness(t)
	pxHistoryStart(t, h, replay.server.URL)
	methods := []string{"px_getHistory", "px_getUnifiedHistory", "px_listHolderRecords"}
	for _, client := range h.clients {
		for _, method := range methods {
			args := []interface{}{pxHistoryAddress}
			if method == "px_listHolderRecords" {
				args = append(args, "budget")
			}
			pxRootCall(t, client, method, args...)
			// These values enter the typed handler and must be recorded as errors.
			args[0] = "invalid"
			pxHistoryFailure(t, client, -32602, pxHistoryParamMessage(method, args), "", method, args...)
		}
	}
	var data metricdata.ResourceMetrics
	require.NoError(t, reader.Collect(t.Context(), &data))
	counts := map[string]uint64{}
	for _, scope := range data.ScopeMetrics {
		for _, instrument := range scope.Metrics {
			if instrument.Name != "px_history_latency" {
				continue
			}
			points, ok := instrument.Data.(metricdata.Histogram[float64])
			require.True(t, ok)
			for _, point := range points.DataPoints {
				endpoint, ok := point.Attributes.Value(attribute.Key("endpoint"))
				require.True(t, ok)
				connection, ok := point.Attributes.Value(attribute.Key("connection"))
				require.True(t, ok)
				success, ok := point.Attributes.Value(attribute.Key("success"))
				require.True(t, ok)
				counts[fmt.Sprintf("%s/%s/%t", endpoint.AsString(), connection.AsString(), success.AsBool())] += point.Count
			}
		}
	}
	for _, method := range methods {
		for _, connection := range []string{string(evmrpc.ConnectionTypeHTTP), string(evmrpc.ConnectionTypeWS)} {
			for _, success := range []bool{true, false} {
				require.Equal(t, uint64(1), counts[fmt.Sprintf("%s/%s/%t", method, connection, success)])
			}
		}
	}
}

