def load_components() -> dict[str, dict[str, KvxValue]]:
    return {
        section.removeprefix("component."): component
        for section, component in load(INVENTORY_PATH).items()
        if section.startswith("component.")
    }


def _doc_cell(value: KvxValue) -> str:
    text = ", ".join(value) if isinstance(value, list) else str(value)
    return text.replace("|", "\\|").replace("\n", "<br>")


def render_doc(components: Mapping[str, Mapping[str, KvxValue]]) -> str:
    """Render retirement records and group their components by owning domain."""
    lines = [
        "# Retired components and their callers",
        "",
        "Generated from `programme/data/retired.kvx`. Do not edit this file by hand.",
        "From the repository root, regenerate it with:",
        "",
        "```sh",
        "PYTHONPATH=spec/layerx-merge python3 -m programme.retired",
        "```",
        "",
        "## Retired components",
        "",
        f"The inventory contains {len(components)} components. Refusals and replacements",
        "below reproduce the inventory; deleted trees name the paths to remove.",
        "An address of 'none' means the record declares no precompile address.",
        "",
        "| Component | Owner domain | Address | Refusal | Deleted trees | Replacement |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    groups: dict[int, list[str]] = {}
    for name, component in sorted(components.items()):
        domain = component["owner_domain"]
        if type(domain) is not int:
            raise ValueError(f"component {name}: owner_domain must be an integer")
        groups.setdefault(domain, []).append(name)
        cells = [
            name,
            domain,
            component.get("address", "none"),
            component["refusal"],
            component["deleted_trees"] or "none",
            component["replacement"],
        ]
        lines.append("| " + " | ".join(_doc_cell(cell) for cell in cells) + " |")
    lines.extend(
        [
            "",
            "## Caller groups",
            "",
            "Components are grouped by their owning domain in the retirement inventory.",
            "Counts describe inventory components, not live caller occurrences.",
            "",
            "| Owner domain | Component count | Components |",
            "| --- | --- | --- |",
        ]
    )
    for domain, names in sorted(groups.items()):
        lines.append(f"| {domain} | {len(names)} | {_doc_cell(names)} |")
    return "\n".join(lines) + "\n"


def diff_against_json(
    json_path: str | PathLike[str],
) -> tuple[set[str], set[str]]:
    """Return names missing from the inventory, then names missing from JSON."""
    with Path(json_path).open(encoding="utf-8") as source:
        json_names = set(json.load(source)["components"])
    inventory_names = set(load_components())
    return json_names - inventory_names, inventory_names - json_names


def stale_rows(root: str | PathLike[str]) -> list[str]:
    """Return inventory disagreements that completed tree deletions do not resolve.

    Ignore refusal-only components with empty deleted_trees when checking names
    missing from JSON: those rows need not appear in the source-tree scan.
    """
    root = Path(root)
    components = load_components()
    added, dropped = diff_against_json(root / "tools/paxeer-x/retired_callers.json")
    stale = set(added)
    for name in dropped:
        deleted_trees = components[name]["deleted_trees"]
        if not isinstance(deleted_trees, list):
            raise ValueError(f"component {name}: deleted_trees must be a list")
        if any(
            (root / tree).exists() or (root / tree).is_symlink()
            for tree in deleted_trees
        ):
            stale.add(name)
    return sorted(stale)


@dataclass(frozen=True)
class RefusalResult:
    passed: bool
    count: int
    exit_code: int
    evidence: str


def _count_refusal(command: str, root: str) -> None:
    try:
        count = parity.count_go_tests(command, root)
    except subprocess.CalledProcessError as error:
        print(error.stdout or "", end="")
        print(error.stderr or "", end="", file=sys.stderr)
        raise
    print(json.dumps({"count": count}), flush=True)


def run_refusals(
    table: Mapping[str, Mapping[str, KvxValue]],
    root: str | PathLike[str],
    log_dir: str | PathLike[str],
) -> dict[str, RefusalResult]:
    root = Path(root).resolve()
    directory = (root / log_dir).resolve()
    directory.mkdir(mode=0o700, parents=True, exist_ok=True)
    revision = subprocess.run(
        ["git", "rev-parse", "HEAD"],
        cwd=root,
        capture_output=True,
        text=True,
        check=True,
    ).stdout.strip()
    results: dict[str, RefusalResult] = {}
    for name, row in table.items():
        if name == "meta":
            continue
        if not re.fullmatch(r"refusal\.[A-Za-z0-9_.-]+", name):
            raise ValueError(f"invalid refusal section: {name}")
        command = row["command"]
        if not isinstance(command, str) or shlex.split(command)[:2] != ["go", "test"]:
            raise ValueError(f"{name}: expected a go test command")
        log_path = directory / f"{name}.log"
        exit_code = evidence.run(
            [
                sys.executable,
                "-c",
                "import sys; sys.path.insert(0, sys.argv[1]); "
                "from programme.retired import _count_refusal; "
                "_count_refusal(sys.argv[2], sys.argv[3])",
                str(Path(__file__).resolve().parents[1]),
                command,
                str(root),
            ],
            log_path,
        )
        count = 0
        if exit_code == 0:
            count = json.loads(log_path.read_text(encoding="utf-8"))["count"]
            if type(count) is not int or count < 0:
                raise ValueError(f"{name}: invalid Go test count: {count!r}")
            if count == 0:
                exit_code = 1
        line = evidence.evidence_line(revision, command, exit_code, log_path)
        with (directory / "evidence.log").open("a", encoding="utf-8") as ledger:
            ledger.write(line + "\n")
        print(line, flush=True)
        results[name] = RefusalResult(
            passed=exit_code == 0 and count >= 1,
            count=count,
            exit_code=exit_code,
            evidence=line,
        )
    return results


def callers(component: str, root: str | PathLike[str]) -> list[str]:
    result = subprocess.run(
        [
            "python3",
            "tools/paxeer-x/tests/retired_callers_test.py",
            "--component",
            component,
        ],
        cwd=root,
        capture_output=True,
        text=True,
        check=False,
    )
    if result.returncode not in (0, 1):
        result.check_returncode()
    locations: dict[str, None] = {}
    for line in result.stdout.splitlines():
        match = re.fullmatch(rf"(.+):([1-9][0-9]*): {re.escape(component)}: .+", line)
        if match is None:
            raise ValueError(f"malformed retired caller: {line!r}")
        locations[f"{match[1]}:{match[2]}"] = None
    if bool(locations) != (result.returncode == 1):
        raise ValueError("retired caller findings disagree with scanner exit status")
    return list(locations)


def owners(callers: Iterable[str]) -> dict[str, int]:
    result: dict[str, int] = {}
    for caller in callers:
        location = re.fullmatch(r"(.+):[1-9][0-9]*", caller)
        path = location[1] if location else caller
        relative = PurePosixPath(path)
        if (
            not path
            or relative.is_absolute()
            or ".." in relative.parts
            or str(relative) != path
            or path == "."
        ):
            raise ValueError(f"invalid caller path: {path!r}")
        matches = [
            (len(prefix), domain)
            for domain, prefixes in DOMAIN_PREFIXES.items()
            for prefix in prefixes
            if path == prefix or path.startswith(prefix + "/")
        ]
        if path.startswith("tests/explorer"):
            matches.append((len("tests/explorer"), 14))
        if relative.parent == PurePosixPath("api") and (
            relative.suffix == ".yaml" or relative.name == "README.md"
        ):
            matches.append((len(path), 7))
        if relative.parent == PurePosixPath("."):
            for domain, patterns in DOMAIN_ROOT_FILES.items():
                if any(fnmatchcase(path, pattern) for pattern in patterns):
                    matches.append((len(path), domain))
                    break
        if not matches:
            raise ValueError(f"no owning domain for caller: {path}")
        result[path] = max(matches)[1]
    return result


