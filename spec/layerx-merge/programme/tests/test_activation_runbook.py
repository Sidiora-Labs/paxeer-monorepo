from pathlib import Path

from programme.activation import (
    GOLDEN_PATH,
    KNOWN_UPGRADE_PLANS,
    load_plans,
    render_runbook,
)
from programme.kvx import load

RUNBOOK_PATH = Path(__file__).resolve().parents[2] / "docs/activation-runbook.md"


def test_runbook_matches_render() -> None:
    plans = load_plans()
    goldens = load(GOLDEN_PATH)
    rendered = render_runbook(plans, goldens)
    expected_goldens = (
        "accepted",
        "no-leaders",
        "lastseq",
        "no-key",
        "bad-genesis",
        "custody-release",
        "anchor-retired",
    )

    assert RUNBOOK_PATH.read_bytes() == rendered.encode("utf-8")
    assert rendered.startswith(
        "# Activation runbook\n\n"
        "Generated from `programme/data/activation-plan.kvx` and\n"
        "`programme/data/goldens/merge-bringup.kvx`. Do not edit this file by hand.\n"
    )
    assert "PYTHONPATH=spec/layerx-merge python3 -m programme.activation" in rendered
    for section in ("Plans", "Merge stores", "Bring-up checks", "Refusals"):
        assert f"\n## {section}\n" in rendered
    assert KNOWN_UPGRADE_PLANS == (
        "v6.9",
        "v6.10",
        "v6.12.0",
        "v7.0",
        "v7.0-anchor-store-delete",
    )
    assert tuple(plan["name"] for plan in plans) == KNOWN_UPGRADE_PLANS
    assert len([plan for plan in plans if plan["name"] in KNOWN_UPGRADE_PLANS]) == 5
    plan_table = rendered.split("\n## Plans\n", 1)[1].split("\n## ", 1)[0]
    for name in KNOWN_UPGRADE_PLANS:
        assert f"\n| {name} |" in plan_table
    merge_stores = rendered.split("\n## Merge stores\n", 1)[1].split("\n## ", 1)[0]
    expected_stores = (
        ("SequencerStoreKey", "sequencer"),
        ("LayerXLedgerStoreKey", "layerxledger"),
        ("LayerXAuthStoreKey", "layerxauth"),
        ("LayerXPayStoreKey", "layerxpay"),
        ("LayerXChainsStoreKey", "layerxchains"),
        ("LayerXProgramsStoreKey", "layerxprograms"),
        ("LayerXAgentStoreKey", "layerxagent"),
        ("LayerXHostStoreKey", "lxphost"),
    )
    assert next(plan for plan in plans if plan["name"] == "v7.0")["store_added"] == [
        store for _, store in expected_stores
    ]
    for constant, store in expected_stores:
        assert f"| `storekeys.{constant}` | `{store}` |" in merge_stores
    assert (
        "Only the later `v7.0-anchor-store-delete` store loader deletes `layerxanchor`"
        in merge_stores
    )
    assert (
        "registered `runAnchorStoreDeleteUpgrade` handler requires `v7.0`" in merge_stores
    )
    assert "completed at a positive height below the deletion height" in merge_stores
    for plan in plans:
        assert plan["name"] in rendered
        assert plan["handler"] in rendered
        for store in [*plan["store_added"], *plan["store_deleted"]]:
            assert store in rendered
    assert tuple(section.removeprefix("golden.") for section in goldens) == expected_goldens
    assert tuple(
        line.removeprefix("### ")
        for line in rendered.splitlines()
        if line.startswith("### ")
    ) == expected_goldens
    assert sum("expect_text" in fields for fields in goldens.values()) == 4
    for section, fields in goldens.items():
        assert f"\n### {section.removeprefix('golden.')}\n" in rendered
        assert fields["command"] in rendered
        assert fields["test"] in rendered
        if "expect_text" in fields:
            assert fields["expect_text"] in rendered
