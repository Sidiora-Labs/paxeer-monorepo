static const nfc_property_range *nfc_property(uint32_t codepoint)
{
    size_t low = 0U;
    size_t high = sizeof(nfc_properties) / sizeof(nfc_properties[0]);
    while (low < high) {
        size_t middle = low + (high - low) / 2U;
        const nfc_property_range *property = &nfc_properties[middle];
        if (codepoint < property->first) high = middle;
        else if (codepoint > property->last) low = middle + 1U;
        else return property;
    }
    return NULL;
}

static uint32_t nfc_starter_prefix(uint32_t starter, uint8_t combining_class)
{
    /* Canonical ordering inserts a new mark before the starter's hidden
     * higher-class marks. Those marks recompose unless the new mark composes
     * with the prefix first (e.g. U+1E0A U+0323 -> U+1E0C U+0307). */
    for (;;) {
        size_t low = 0U;
        size_t high = sizeof(nfc_decompositions) / sizeof(nfc_decompositions[0]);
        uint32_t prefix = starter;
        while (low < high) {
            size_t middle = low + (high - low) / 2U;
            const nfc_starter_decomposition *entry = &nfc_decompositions[middle];
            if (starter < entry->composite) high = middle;
            else if (starter > entry->composite) low = middle + 1U;
            else {
                if (entry->trailing_class > combining_class) prefix = entry->prefix;
                break;
            }
        }
        if (prefix == starter) return starter;
        starter = prefix;
    }
}

static int nfc_can_compose(uint32_t starter, uint32_t following,
                            uint8_t combining_class)
{
    size_t low = 0U;
    size_t high = sizeof(nfc_compositions) / sizeof(nfc_compositions[0]);
    /* UAX #15's algorithmic Hangul L+V and LV+T compositions. */
    if (starter >= 0x1100U && starter <= 0x1112U &&
        following >= 0x1161U && following <= 0x1175U) return 1;
    if (starter >= 0xac00U && starter <= 0xd7a3U &&
        (starter - 0xac00U) % 28U == 0U &&
        following >= 0x11a8U && following <= 0x11c2U) return 1;
    if (combining_class != 0U) starter = nfc_starter_prefix(starter, combining_class);
    while (low < high) {
        size_t middle = low + (high - low) / 2U;
        const nfc_composition_pair *pair = &nfc_compositions[middle];
        if (starter < pair->starter ||
            (starter == pair->starter && following < pair->following))
            high = middle;
        else if (starter > pair->starter || following > pair->following)
            low = middle + 1U;
        else return 1;
    }
    return 0;
}

static int utf8_nfc_is_canonical(const uint8_t *text, size_t length)
{
    size_t i = 0U;
    uint32_t starter = UINT32_MAX;
    uint8_t previous_class = 0U;
    while (i < length) {
        const nfc_property_range *property;
        uint8_t combining_class;
        uint32_t codepoint;
        uint8_t first = text[i++];
        size_t continuation;
        if (first < 0x80U) {
            codepoint = first;
            continuation = 0U;
        } else if (first >= 0xc2U && first <= 0xdfU) {
            codepoint = first & 0x1fU;
            continuation = 1U;
        } else if (first >= 0xe0U && first <= 0xefU) {
            codepoint = first & 0x0fU;
            continuation = 2U;
        } else if (first >= 0xf0U && first <= 0xf4U) {
            codepoint = first & 0x07U;
            continuation = 3U;
        } else return 0;
        if (continuation > length - i) return 0;
        while (continuation != 0U) {
            uint8_t next = text[i++];
            --continuation;
            if ((next & 0xc0U) != 0x80U) return 0;
            codepoint = (codepoint << 6U) | (next & 0x3fU);
        }
        if ((codepoint < 0x80U && first >= 0x80U) ||
            (codepoint < 0x800U && first >= 0xe0U) ||
            (codepoint < 0x10000U && first >= 0xf0U) ||
            codepoint > 0x10ffffU ||
            (codepoint >= 0xd800U && codepoint <= 0xdfffU)) return 0;
        property = nfc_property(codepoint);
        combining_class = property == NULL ? 0U : property->combining_class;
        if (property != NULL && property->excluded != 0U) return 0;
        if (combining_class != 0U && previous_class > combining_class) return 0;
        /* Equal/higher intervening classes block composition. Class zero
         * only composes with the immediately preceding starter (e.g. Hangul). */
        if ((previous_class == 0U || previous_class < combining_class) &&
            nfc_can_compose(starter, codepoint, combining_class)) return 0;
        if (combining_class == 0U) starter = codepoint;
        previous_class = combining_class;
    }
    return 1;
}

lxp_result lxp_codec_write_text(lxp_codec_writer *writer, const char *text,
                                size_t length, uint32_t maximum)
{
    if ((text == NULL && length != 0U) ||
        !utf8_nfc_is_canonical((const uint8_t *)text, length)) {
        return LXP_ERR_NON_CANONICAL;
    }
    return lxp_codec_write_bytes(writer, text, length, maximum);
}

lxp_result lxp_codec_write_seq(lxp_codec_writer *writer, uint32_t count,
                               uint32_t maximum)
{
    if (count > maximum) return LXP_ERR_LENGTH_LIMIT;
    return lxp_codec_write_u32(writer, count);
}

lxp_result lxp_codec_seq_check_sorted(const lxp_byte_span *keys, size_t count)
{
    size_t i;
    if (keys == NULL && count != 0U) return LXP_ERR_NON_CANONICAL;
    for (i = 1U; i < count; ++i) {
        size_t common = keys[i - 1U].length < keys[i].length ?
                        keys[i - 1U].length : keys[i].length;
        int order = memcmp(keys[i - 1U].bytes, keys[i].bytes, common);
        if (order > 0 || (order == 0 &&
            keys[i - 1U].length >= keys[i].length)) {
            return LXP_ERR_UNSORTED_SEQUENCE;
        }
    }
    return LXP_OK;
}

lxp_result lxp_codec_write_tag(lxp_codec_writer *writer, uint8_t tag,
                               uint8_t maximum_tag)
{
    if (tag > maximum_tag) return LXP_ERR_INVALID_TAG;
    return lxp_codec_write_u8(writer, tag);
}

lxp_result lxp_codec_read_tag(lxp_codec_reader *reader, uint8_t maximum_tag,
                              uint8_t *tag)
{
    lxp_result result = lxp_codec_read_u8(reader, tag);
    if (result != LXP_OK) return result;
    return *tag <= maximum_tag ? LXP_OK : LXP_ERR_INVALID_TAG;
}

lxp_result lxp_codec_write_struct_header(lxp_codec_writer *writer,
                                         uint16_t structure_tag)
{
    return lxp_codec_write_struct_header_version(
        writer, structure_tag, (uint16_t)LXP_PROTOCOL_VERSION_LEGACY);
}

lxp_result lxp_codec_write_struct_header_version(lxp_codec_writer *writer,
                                                 uint16_t structure_tag,
                                                 uint16_t protocol_version)
{
    lxp_result result;
    if (structure_tag == 0U ||
        !lxp_protocol_version_supported(protocol_version))
        return LXP_ERR_INVALID_TAG;
    result = lxp_codec_write_u16(writer, protocol_version);
    if (result != LXP_OK) return result;
    return lxp_codec_write_u16(writer, structure_tag);
}

lxp_result lxp_codec_read_struct_header(lxp_codec_reader *reader,
                                        uint16_t expected_structure_tag)
{
    uint16_t ignored;
    return lxp_codec_read_struct_header_version(
        reader, expected_structure_tag, &ignored);
}

lxp_result lxp_codec_read_struct_header_version(
    lxp_codec_reader *reader, uint16_t expected_structure_tag,
    uint16_t *protocol_version)
{
    uint16_t version;
    uint16_t structure_tag;
    lxp_result result = lxp_codec_read_u16(reader, &version);
    if (result != LXP_OK) return result;
    result = lxp_codec_read_u16(reader, &structure_tag);
    if (result != LXP_OK) return result;
    if (protocol_version == NULL || !lxp_protocol_version_supported(version) ||
        structure_tag != expected_structure_tag || expected_structure_tag == 0U) {
        return LXP_ERR_VERSION_UNSUPPORTED;
    }
    *protocol_version = version;
    return LXP_OK;
}

lxp_result lxp_codec_finish(const lxp_codec_reader *reader)
{
    if (reader == NULL || reader->offset > reader->length) {
        return LXP_ERR_TRUNCATED;
    }
    return reader->offset == reader->length ? LXP_OK : LXP_ERR_TRAILING_BYTES;
}

lxp_result lxp_codec_reject_unknown_field(uint16_t field_id,
                                          uint16_t maximum_field_id)
{
    return field_id == 0U || field_id > maximum_field_id ?
           LXP_ERR_UNKNOWN_FIELD : LXP_OK;
}
