func TestRepairM_373_PublicationContract(t *testing.T) {
	var help bytes.Buffer
	if err := proposals.Run([]string{"-h"}, &help); !errors.Is(err, flag.ErrHelp) {
		t.Fatalf("help returned %v, want flag.ErrHelp", err)
	}
	mainFile, err := parser.ParseFile(token.NewFileSet(), "main.go", nil, parser.ParseComments)
	if err != nil {
		t.Fatal(err)
	}
	if mainFile.Doc == nil {
		t.Fatal("command has no package documentation")
	}
	producer, err := parser.ParseFile(token.NewFileSet(), filepath.Join("..", "..", "proposals.go"), nil, parser.ParseComments)
	if err != nil {
		t.Fatal(err)
	}
	var runDoc string
	for _, decl := range producer.Decls {
		if fn, ok := decl.(*ast.FuncDecl); ok && fn.Name.Name == "Run" && fn.Doc != nil {
			runDoc = fn.Doc.Text()
		}
	}
	for name, text := range map[string]string{"command": mainFile.Doc.Text(), "Run": runDoc, "help": help.String()} {
		t.Run(name, func(t *testing.T) {
			text = strings.Join(strings.Fields(text), " ")
			for _, obligation := range []string{
				"bodies, proposals and readback are staged before publication",
				"validation and initial staging failures publish no artifacts",
				"not atomic across destinations",
				"complete outputs from an incomplete set",
				"Do not submit an incomplete set",
				".<directory>.bridge-publication.json",
				"outermost directory containing the bodies",
				".bridge-stage-* siblings",
				"rerun the same arguments with unchanged inputs",
				"destination paths, generated bytes and all published and staged files before resuming",
				"unrelated or changed files are refused rather than overwritten",
				"Output paths are reported only after the entire publication succeeds and the journal has been removed",
			} {
				if !strings.Contains(text, obligation) {
					t.Errorf("%s lacks publication obligation %q", name, obligation)
				}
			}
			if strings.Contains(text, "writes no partial output when it refuses") {
				t.Error("retained unconditional no-partial-output promise")
			}
		})
	}
}

type repairM373Fixture struct {
	root, config, bodies, governance, readback string
	args                                       []string
	bundle                                     proposals.Bundle
	expected                                   proposals.Readback
}

func repairM373Input(t *testing.T, chain string) repairM373Fixture {
	t.Helper()
	fixtures := filepath.Join("..", "..", "testdata")
	legacy, err := proposals.LoadChainConfig(filepath.Join(fixtures, chain+".json"))
	if err != nil {
		t.Fatal(err)
	}
	manifestPath := filepath.Join(fixtures, "attestors.json")
	manifest, err := proposals.LoadAttestorManifest(manifestPath)
	if err != nil {
		t.Fatal(err)
	}
	path, err := chainconfig.Path(filepath.Join("..", "..", "..", "..", "..", ".."), chain)
	if err != nil {
		t.Fatal(err)
	}
	canonical, err := chainconfig.Load(path)
	if err != nil {
		t.Fatal(err)
	}
	canonical.Owner, canonical.Attestors = legacy.Owner, legacy.Attestors
	vault := legacy.Vault
	if canonical.Solana != nil {
		canonical.Solana.ProgramID = legacy.ProgramID
		program, err := vectors.Key(canonical.Solana.ProgramID)
		if err != nil {
			t.Fatal(err)
		}
		handle, err := vectors.VaultHandle(program)
		if err != nil {
			t.Fatal(err)
		}
		vault = handle.Hex()
	}
	root := t.TempDir()
	config := filepath.Join(root, chain, "config.json")
	if err := os.Mkdir(filepath.Dir(config), 0o755); err != nil {
		t.Fatal(err)
	}
	raw, err := json.Marshal(canonical)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(config, raw, 0o644); err != nil {
		t.Fatal(err)
	}
	canonical, err = chainconfig.Load(config)
	if err != nil {
		t.Fatal(err)
	}
	cfg, err := proposals.FromChainConfig(canonical, legacy.Authority, vault)
	if err != nil {
		t.Fatal(err)
	}
	bundle, err := proposals.Generate(cfg, manifest)
	if err != nil {
		t.Fatal(err)
	}
	expected, err := proposals.ReadbackOf(canonical, bundle)
	if err != nil {
		t.Fatal(err)
	}
	bodies, governance := filepath.Join(root, "bodies"), filepath.Join(root, "governance")
	readback := filepath.Join(root, "missing", "readback.json")
	return repairM373Fixture{
		root: root, config: config, bodies: bodies, governance: governance, readback: readback,
		args: []string{"-manifest", manifestPath, "-authority", legacy.Authority, "-vault", vault,
			"-readback", readback, "-proposals", governance, config, bodies},
		bundle: bundle, expected: expected,
	}
}

func (f repairM373Fixture) assertUnpublished(t *testing.T, report string) {
	t.Helper()
	if report != "" {
		t.Fatalf("failed generation reported success: %s", report)
	}
	for _, path := range []string{f.bodies, f.governance, f.readback} {
		if _, err := os.Lstat(path); !os.IsNotExist(err) {
			t.Fatalf("failed generation published %s: %v", path, err)
		}
	}
	entries, err := os.ReadDir(f.root)
	if err != nil {
		t.Fatal(err)
	}
	for _, entry := range entries {
		if strings.HasPrefix(entry.Name(), ".") {
			t.Errorf("initial failure retained publication state %s", entry.Name())
		}
	}
}

func repairM373SameMessage(t *testing.T, path string, got, want proto.Message) {
	t.Helper()
	gotBytes, err := proto.Marshal(got)
	if err != nil {
		t.Fatal(err)
	}
	wantBytes, err := proto.Marshal(want)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(gotBytes, wantBytes) {
		t.Fatalf("%s differs from the generated module content", path)
	}
}

func (f repairM373Fixture) assertComplete(t *testing.T, report string) {
	t.Helper()
	bodies, err := f.bundle.Files()
	if err != nil {
		t.Fatal(err)
	}
	messages := []sdk.Msg{&f.bundle.Register, &f.bundle.Attestors}
	for i := range f.bundle.Caps {
		messages = append(messages, &f.bundle.Caps[i])
	}
	var paths []string
	for i, file := range bodies {
		path := filepath.Join(f.bodies, file.Name)
		raw, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		decoded, err := proposals.DecodeBody(raw)
		if err != nil {
			t.Fatal(err)
		}
		if !bytes.Equal(raw, file.Body) {
			t.Fatalf("%s differs from the generated body bytes", path)
		}
		repairM373SameMessage(t, path, decoded, messages[i])
		if err := decoded.ValidateBasic(); err != nil {
			t.Fatal(err)
		}
		paths = append(paths, path)
	}
	contents, err := f.bundle.Proposals()
	if err != nil {
		t.Fatal(err)
	}
	for _, content := range contents {
		path := filepath.Join(f.governance, content.Name)
		raw, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		decoded, err := proposals.DecodeProposal(raw)
		if err != nil {
			t.Fatal(err)
		}
		repairM373SameMessage(t, path, decoded, content.Content)
		paths = append(paths, path)
	}
	raw, err := os.ReadFile(f.readback)
	if err != nil {
		t.Fatal(err)
	}
	decoder := json.NewDecoder(bytes.NewReader(raw))
	decoder.DisallowUnknownFields()
	var readback proposals.Readback
	if err := decoder.Decode(&readback); err != nil {
		t.Fatal(err)
	}
	var tail any
	if err := decoder.Decode(&tail); err != io.EOF {
		t.Fatalf("unexpected readback tail: %v", err)
	}
	if !reflect.DeepEqual(readback, f.expected) {
		t.Fatalf("readback differs from the generated bundle: got %+v, want %+v", readback, f.expected)
	}
	paths = append(paths, f.readback)
	if want := strings.Join(paths, "\n") + "\n"; report != want {
		t.Fatalf("reported paths differ: got %q, want %q", report, want)
	}
	for dir, count := range map[string]int{f.bodies: len(bodies), f.governance: len(contents)} {
		entries, err := os.ReadDir(dir)
		if err != nil {
			t.Fatal(err)
		}
		if len(entries) != count {
			t.Fatalf("%s contains %d artifacts, want %d", dir, len(entries), count)
		}
	}
	if err := filepath.WalkDir(f.root, func(path string, entry os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if strings.HasPrefix(entry.Name(), ".bridge-") || strings.HasSuffix(entry.Name(), ".bridge-publication.json") {
			t.Errorf("completed publication retained journal or stage %s", path)
		}
		return nil
	}); err != nil {
		t.Fatal(err)
	}
}

func TestRepairM_373_StagingFailureAndRetry(t *testing.T) {
	for _, chain := range []string{"ethereum", "solana"} {
		t.Run(chain, func(t *testing.T) {
			fixture := repairM373Input(t, chain)
			var report bytes.Buffer
			err := proposals.Run(fixture.args, &report)
			if !errors.Is(err, os.ErrNotExist) || !strings.Contains(err.Error(), filepath.Dir(fixture.readback)) {
				t.Fatalf("want missing readback-parent refusal after staging bodies and proposals, got %v", err)
			}
			fixture.assertUnpublished(t, report.String())
			if err := os.Mkdir(filepath.Dir(fixture.readback), 0o755); err != nil {
				t.Fatal(err)
			}
			if err := proposals.Run(fixture.args, &report); err != nil {
				t.Fatalf("retry with identical arguments: %v", err)
			}
			fixture.assertComplete(t, report.String())
		})
	}
}

func TestRepairM_373_ValidationRefusal(t *testing.T) {
	fixture := repairM373Input(t, "ethereum")
	raw, err := os.ReadFile(fixture.config)
	if err != nil {
		t.Fatal(err)
	}
	var cfg chainconfig.ChainConfig
	if err := json.Unmarshal(raw, &cfg); err != nil {
		t.Fatal(err)
	}
	cfg.Threshold = 0
	raw, err = json.Marshal(cfg)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(fixture.config, raw, 0o644); err != nil {
		t.Fatal(err)
	}
	var report bytes.Buffer
	if err := proposals.Run(fixture.args, &report); err == nil || !strings.Contains(err.Error(), "threshold") || !strings.Contains(err.Error(), fixture.config) {
		t.Fatalf("want validation refusal naming configuration and threshold, got %v", err)
	}
	fixture.assertUnpublished(t, report.String())
}
