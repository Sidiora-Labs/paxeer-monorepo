// Command paxeer-bridge-proposals reads one chain configuration and the
// committed attestor-set manifest and writes the governance bodies that open
// that chain on Paxeer X Network into an output directory.
//
// It refuses a placeholder or zero authority, owner or attestor, a zero
// threshold or one above the attestor count and a zero cap, naming the file and
// the field. All requested bodies, proposals and readback are staged before
// publication; validation and initial staging failures publish no artifacts.
//
// Publication is not atomic across destinations: a failure can leave some
// complete outputs from an incomplete set. Do not submit an incomplete set.
// The recovery journal .<directory>.bridge-publication.json is beside the
// outermost directory containing the bodies. Preserve it and the .bridge-stage-*
// siblings. After resolving the filesystem error, rerun the same arguments with
// unchanged inputs. Recovery checks destination paths, generated bytes and all
// published and staged files before resuming; unrelated or changed files are
// refused rather than overwritten. Output paths are reported only after the
// entire publication succeeds and the journal has been removed.
//
//	paxeer-bridge-proposals [-manifest <path>] [-authority <bech32> -vault <address> [-readback <path>]] [-proposals <directory>] <chain-configuration.json> <output-directory>
package main

import (
	"fmt"
	"os"

	"github.com/Sidiora-Labs/Paxeer-X-Network/services/bridge/deploy/proposals"
)

func main() {
	if err := proposals.Run(os.Args[1:], os.Stdout); err != nil {
		fmt.Fprintf(os.Stderr, "%s: %v\n", proposals.CommandName, err)
		os.Exit(1)
	}
}
