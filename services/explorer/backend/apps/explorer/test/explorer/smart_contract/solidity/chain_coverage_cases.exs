defmodule Explorer.SmartContract.Solidity.ChainCoverageCases do
  import ExUnit.Assertions
  import Explorer.Factory

  alias Explorer.Chain.{Address, ContractMethod, Data, SmartContract}
  alias Explorer.Repo
  alias Explorer.SmartContract.Solidity.{CodeCompiler, Publisher, Verifier}

  defmacro compiler_cases do
    quote do
      test "solidity-compiler-chain-coverage retains name, suffix and compilation errors" do
        Explorer.SmartContract.Solidity.ChainCoverageCases.compiler_contract_info()
      end

      test "solidity-compiler-chain-coverage consumes recorded compiler output through the contract schema" do
        Explorer.SmartContract.Solidity.ChainCoverageCases.compiler_result_to_schema()
      end
    end
  end

  defmacro publisher_cases do
    quote do
      test "solidity-publisher-chain-coverage persists all contract fields and ABI methods" do
        Explorer.SmartContract.Solidity.ChainCoverageCases.publish_recording()
      end

      test "solidity-publisher-chain-coverage persists recorded constructor arguments" do
        Explorer.SmartContract.Solidity.ChainCoverageCases.publish_constructor()
      end

      test "solidity-publisher-chain-coverage allows source and name reverification" do
        Explorer.SmartContract.Solidity.ChainCoverageCases.republish_recording()
      end

      test "solidity-publisher-chain-coverage returns an invalid changeset for invalid source" do
        Explorer.SmartContract.Solidity.ChainCoverageCases.reject_invalid_publication()
      end
    end
  end

  defmacro verifier_cases do
    quote do
      test "solidity-verifier-chain-coverage matches legacy and modern recorded bytecode" do
        Explorer.SmartContract.Solidity.ChainCoverageCases.verify_recordings()
      end

      test "solidity-verifier-chain-coverage rejects mismatched generated bytecode" do
        Explorer.SmartContract.Solidity.ChainCoverageCases.reject_generated_bytecode()
      end

      test "solidity-verifier-chain-coverage rejects mismatched compiler metadata" do
        Explorer.SmartContract.Solidity.ChainCoverageCases.reject_compiler_version()
      end

      test "solidity-verifier-chain-coverage detects constructor arguments and rejects incorrect explicit arguments" do
        Explorer.SmartContract.Solidity.ChainCoverageCases.verify_constructor_arguments()
      end

      test "solidity-verifier-chain-coverage requires indexed creation data" do
        Explorer.SmartContract.Solidity.ChainCoverageCases.reject_missing_creation()
      end

      test "solidity-verifier-chain-coverage requires deployed bytecode" do
        Explorer.SmartContract.Solidity.ChainCoverageCases.reject_missing_deployed_bytecode()
      end
    end
  end

  def compiler_contract_info do
    recording = contract_code_info()
    info = compiler_result(recording)

    assert {:error, :name} == CodeCompiler.get_contract_info(%{recording.name => info}, "diff_name")
    assert {:error, :compilation} == CodeCompiler.get_contract_info(%{}, recording.name)
    assert info == CodeCompiler.get_contract_info(%{recording.name => info}, recording.name)
    assert info == CodeCompiler.get_contract_info(%{(":" <> recording.name) => info}, recording.name)
  end

  def compiler_result_to_schema do
    context = indexed_recording(contract_code_info())
    assert context.candidate["abi"] == context.recording.abi
    assert context.candidate["bytecode"] == without_prefix(context.recording.tx_input)
    assert context.candidate["deployedBytecode"] == without_prefix(context.recording.bytecode)
    assert_published(context)
  end

  def publish_recording do
    context = indexed_recording(contract_code_info_modern_compiler())
    assert_published(context)

    for selector <- context.recording.abi do
      [parsed] = ABI.parse_specification([selector])
      assert Repo.get_by(ContractMethod, abi: selector, identifier: %Data{bytes: parsed.method_id})
    end
  end

  def publish_constructor do
    context = indexed_recording(contract_code_info_with_constructor_arguments())
    stored = assert_published(context)
    assert stored.constructor_arguments == context.recording.constructor_args
    assert stored.optimization_runs == context.recording.optimization_runs
  end

  def republish_recording do
    context = indexed_recording(contract_code_info())
    original = assert_published(context)
    updated_name = "AnotherContractName"

    updated_source =
      String.replace(context.recording.source_code, "contract #{context.recording.name}", "contract #{updated_name}")

    context = %{
      context
      | candidate: Map.put(context.candidate, "name", updated_name),
        params: Map.put(context.params, "name", updated_name),
        input: put_in(context.input, ["sources", context.file_path, "content"], updated_source),
        recording: %{context.recording | name: updated_name, source_code: updated_source}
    }

    updated = assert_published(context)
    assert updated.id == original.id
    assert updated.name == updated_name
    assert updated.contract_source_code == updated_source
  end

  def reject_invalid_publication do
    context = indexed_recording(contract_code_info())

    params = %{
      "contract_source_code" => "",
      "compiler_version" => "",
      "name" => "",
      "optimization" => ""
    }

    assert {:error, %Ecto.Changeset{valid?: false, action: :insert} = changeset} =
             Publisher.publish(context.address.hash, params)

    assert changeset.errors != []
    assert_unpublished(context)
  end

  def verify_recordings do
    for recording <- [contract_code_info(), contract_code_info_modern_compiler()] do
      context = indexed_recording(recording)
      assert {:ok, %{abi: abi}, additional} = verify(context)
      assert abi == recording.abi
      assert additional["contract_source_code"] == recording.source_code
      assert additional["name"] == recording.name
      assert additional["file_path"] == context.file_path
      assert additional["compiler_settings"] == context.input["settings"]
      assert_unpublished(context)
    end
  end

  def reject_generated_bytecode do
    context = indexed_recording(contract_code_info())
    context = %{context | candidate: Map.put(context.candidate, "bytecode", "deadbeef")}
    assert {:error, {:error, :generated_bytecode}} = verify(context)
    assert_unpublished(context)
  end

  def reject_compiler_version do
    context = indexed_recording(contract_code_info_with_constructor_arguments())

    altered =
      String.replace(context.candidate["deployedBytecode"], "64736f6c63430008040033", "64736f6c63430008050033")

    refute altered == context.candidate["deployedBytecode"]
    context = %{context | candidate: Map.put(context.candidate, "deployedBytecode", altered)}
    assert {:error, {:error, :compiler_version}} = verify(context)
    assert_unpublished(context)
  end

  def verify_constructor_arguments do
    context = indexed_recording(contract_code_info_with_constructor_arguments())
    assert {:ok, %{abi: abi, constructor_arguments: arguments}, _} = verify(context)
    assert abi == context.recording.abi
    assert arguments == context.recording.constructor_args

    params =
      context.params
      |> Map.put("autodetect_constructor_args", false)
      |> Map.put("constructor_arguments", "deadbeef")

    assert {:error, {:error, :constructor_arguments}} = verify(%{context | params: params})
    assert_unpublished(context)
  end

  def reject_missing_creation do
    context = indexed_recording(contract_code_info(), creation?: false)
    assert {:error, {:error, :no_creation_data}} = verify(context)
    assert_unpublished(context)
  end

  def reject_missing_deployed_bytecode do
    context = indexed_recording(contract_code_info(), deployed_bytecode: "0x")
    assert {:error, {:error, :deployed_bytecode}} = verify(context)
    assert_unpublished(context)
  end

  defp indexed_recording(recording, options \\ []) do
    address = insert(:contract_address, contract_code: Keyword.get(options, :deployed_bytecode, recording.bytecode))

    if Keyword.get(options, :creation?, true) do
      :transaction
      |> insert(created_contract_address_hash: address.hash, input: recording.tx_input)
      |> with_block(status: :ok)
    end

    file_path = "#{recording.name}.sol"
    candidate = CodeCompiler.get_contract_info(%{recording.name => compiler_result(recording)}, recording.name)
    candidate = Map.put(candidate, "file_path", file_path)

    input = %{
      "language" => "Solidity",
      "sources" => %{file_path => %{"content" => recording.source_code}},
      "settings" => %{
        "optimizer" => %{"enabled" => recording.optimized, "runs" => Map.get(recording, :optimization_runs, 200)}
      }
    }

    params = %{
      "name" => recording.name,
      "compiler_version" => recording.version,
      "evm_version" => "default",
      "autodetect_constructor_args" => true
    }

    %{recording: recording, address: address, candidate: candidate, input: input, params: params, file_path: file_path}
  end

  defp compiler_result(recording) do
    constructor_arguments = Map.get(recording, :constructor_args, "")

    %{
      "abi" => recording.abi,
      "name" => recording.name,
      "bytecode" => recording.tx_input |> without_prefix() |> String.replace_suffix(constructor_arguments, ""),
      "deployedBytecode" => without_prefix(recording.bytecode)
    }
  end

  defp verify(context) do
    Verifier.verify_standard_json_candidates(
      context.address.hash,
      context.params,
      Jason.encode!(context.input),
      [context.candidate]
    )
  end

  defp assert_published(context) do
    assert {:ok, verified, additional} = verify(context)
    assert verified.abi == context.recording.abi
    params = Map.merge(context.params, additional)
    params = Map.put(params, "constructor_arguments", Map.get(verified, :constructor_arguments))

    assert {:ok, %SmartContract{} = published} =
             Publisher.publish_smart_contract(context.address.hash, params, verified.abi, true)

    stored = Repo.get_by!(SmartContract, address_hash: context.address.hash)
    assert stored.id == published.id
    assert stored.address_hash == context.address.hash
    assert stored.name == context.recording.name
    assert stored.compiler_version == context.recording.version
    assert stored.optimization == context.recording.optimized
    assert stored.contract_source_code == context.recording.source_code
    assert stored.constructor_arguments == Map.get(context.recording, :constructor_args)
    assert stored.abi == context.recording.abi
    assert stored.file_path == context.file_path
    assert stored.compiler_settings == context.input["settings"]
    assert stored.evm_version == "default"
    assert Repo.get!(Address, context.address.hash).verified
    stored
  end

  defp assert_unpublished(context) do
    assert Repo.get_by(SmartContract, address_hash: context.address.hash) == nil
    refute Repo.get!(Address, context.address.hash).verified
  end

  defp without_prefix(bytecode), do: String.replace_prefix(bytecode, "0x", "")
end
